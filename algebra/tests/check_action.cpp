// Checks of morphe/algebra/action.hpp: actions built from images are refused when they are not
// actions or their sign is not a homomorphism; the orbit–stabiliser theorem and Burnside's count
// for the regular actions of every group of morphe's catalogue up to order 24 and for the action
// of S₄ on the left cosets of each of its subgroups found as stabilisers; the orbits of words of
// length n, with and without reversing elements, by Burnside's lemma against enumeration.

#include <morphe/algebra/action.hpp>
#include <morphe/algebra/finite_group.hpp>
#include <morphe/check.hpp>

#include <algorithm>
#include <set>
#include <stdexcept>
#include <string>
#include <vector>

namespace ma = morphe::algebra;
using morphe::arithmetic::Integer;

namespace {

std::vector<std::vector<std::uint32_t>> words(std::size_t sigma, std::size_t n) {
  std::vector<std::vector<std::uint32_t>> out;
  std::vector<std::uint32_t> w(n, 0);
  for (;;) {
    out.push_back(w);
    std::size_t i = 0;
    while (i < n && ++w[i] == sigma) w[i++] = 0;
    if (i == n) break;
  }
  return out;
}

// The action of G on the left cosets of a subgroup H (given as a set of elements).
ma::GroupAction on_cosets(const ma::FiniteGroup& G, const std::vector<std::uint32_t>& H) {
  std::vector<std::uint32_t> coset_of(G.order(), UINT32_MAX);
  std::vector<std::uint32_t> reps;
  for (std::uint32_t g = 0; g < G.order(); g++) {
    if (coset_of[g] != UINT32_MAX) continue;
    for (std::uint32_t h : H) coset_of[G.mul(g, h)] = static_cast<std::uint32_t>(reps.size());
    reps.push_back(g);
  }
  std::vector<std::vector<std::uint32_t>> images(G.order());
  for (std::uint32_t g = 0; g < G.order(); g++)
    for (std::uint32_t c = 0; c < reps.size(); c++) images[g].push_back(coset_of[G.mul(g, reps[c])]);
  return ma::GroupAction::from_images(G, reps.size(), images);
}

}  // namespace

int main() {
  morphe::Suite s;

  {
    const auto z2 = ma::cyclic(2);
    bool refused = false;
    try { (void)ma::GroupAction::from_images(z2, 3, {{0, 1, 2}, {1, 2, 0}}); } catch (const std::invalid_argument&) { refused = true; }
    s.require("a map that is not an action is refused (a 3-cycle for an involution)", refused);
    refused = false;
    try { (void)ma::GroupAction::from_images(z2, 2, {{0, 1}, {1, 0}}, {-1, 1}); } catch (const std::invalid_argument&) { refused = true; }
    s.require("a sign that is not a homomorphism is refused", refused);
  }
  {
    std::vector<ma::FiniteGroup> groups{ma::cyclic(1), ma::cyclic(6), ma::dihedral(4), ma::quaternion(), ma::symmetric(3), ma::symmetric(4), ma::alternating(4),
                                       ma::direct_product(ma::cyclic(2), ma::cyclic(2))};
    bool ok = true;
    for (const auto& G : groups) {
      const auto r = ma::regular_action(G);
      ok = ok && r.orbit_count() == 1 && r.burnside() == 1 && r.stabiliser(0).size() == 1;
    }
    s.require("the regular action of every group is free and transitive", ok);
    // S₄ on the cosets of the stabilisers of its own regular action's subgroups: the subgroups
    // generated by each element.
    const auto S4 = ma::symmetric(4);
    bool os = true, burnside = true;
    std::size_t actions = 0;
    std::set<std::vector<std::uint32_t>> seen;
    for (std::uint32_t g = 0; g < S4.order(); g++) {
      std::vector<std::uint32_t> H{0};
      for (std::uint32_t x = g; x != 0; x = S4.mul(x, g)) H.push_back(x);
      std::sort(H.begin(), H.end());
      if (!seen.insert(H).second) continue;
      const auto a = on_cosets(S4, H);
      for (std::uint32_t x = 0; x < a.degree; x++) os = os && a.orbit(x).size() * a.stabiliser(x).size() == S4.order();
      burnside = burnside && a.burnside() == a.orbit_count();
      actions++;
    }
    s.require("the orbit–stabiliser theorem on S₄ acting on the cosets of its cyclic subgroups", os, std::to_string(actions) + " actions");
    s.require("Burnside's count equals the number of orbits", burnside);
  }
  {
    // Words: the Klein group on four letters by translations, with and without a reversing factor.
    const auto v4 = ma::direct_product(ma::cyclic(2), ma::cyclic(2));
    const auto letters = ma::regular_action(v4);
    const auto v8 = ma::direct_product(v4, ma::cyclic(2));
    std::vector<std::vector<std::uint32_t>> images(8);
    std::vector<std::int8_t> sign(8);
    for (std::uint32_t e = 0; e < 8; e++) {
      for (std::uint32_t x = 0; x < 4; x++) images[e].push_back(letters.act(e / 2, x));
      sign[e] = e % 2 ? -1 : 1;
    }
    const auto signed_action = ma::GroupAction::from_images(v8, 4, images, sign);
    // S₃ on three letters with a reversing factor.
    const auto s3 = ma::symmetric(3);
    std::vector<std::uint32_t> H{0};
    for (std::uint32_t g = 1; g < s3.order() && H.size() < 2; g++)
      if (s3.element_order(g) == 2) H.push_back(g);
    const auto on3 = on_cosets(s3, H);
    const auto s3z2 = ma::direct_product(s3, ma::cyclic(2));
    std::vector<std::vector<std::uint32_t>> images3(12);
    std::vector<std::int8_t> sign3(12);
    for (std::uint32_t e = 0; e < 12; e++) {
      for (std::uint32_t x = 0; x < 3; x++) images3[e].push_back(on3.act(e / 2, x));
      sign3[e] = e % 2 ? -1 : 1;
    }
    const auto signed3 = ma::GroupAction::from_images(s3z2, 3, images3, sign3);
    bool ok = true;
    for (const auto* a : {&letters, &signed_action, &signed3})
      for (std::size_t n = 0; n <= 6; n++) {
        std::set<std::vector<std::uint32_t>> canon;
        for (const auto& w : words(a->degree, n)) canon.insert(a->canonical(w));
        ok = ok && a->word_orbits(n) == Integer(static_cast<unsigned long long>(canon.size()));
      }
    s.require("orbits of words by Burnside's lemma against enumeration, with and without reversal", ok);
  }
  return s.done();
}
