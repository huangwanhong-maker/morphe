// Checks of morphe/algebra/field_matrix.hpp and group_algebra.hpp. Linear algebra over a field
// against morphe's linear algebra over ℤ (ranks against the Smith form, determinants against
// Bareiss's) and by its own identities over ℚ(ζ_5). The group algebra: associativity and unit of
// the convolution; on nine groups the central idempotents e_χ from the Dixon–Schneider table,
// e_χ² = e_χ, e_χ e_ψ = 0, Σ e_χ = 1, each central, and each block ℂ[G] e_χ of dimension χ(1)²
// measured by exact elimination (C[G] ≅ ⊕ M_{χ(1)}); isotypic components that sum to f and lie
// in their blocks. Over ℚ: the blocks are Galois orbits, their idempotents rational, orthogonal
// and summing to 1, of dimension |orbit| χ(1)², as many as the conjugacy classes of cyclic
// subgroups; and ℚ[C_n] ≅ ⊕_{d | n} ℚ(ζ_d) for n ≤ 18, each block of dimension φ(d) and generated
// by a root of Φ_d.

#include <morphe/algebra/determinant.hpp>
#include <morphe/algebra/field_matrix.hpp>
#include <morphe/algebra/group_algebra.hpp>
#include <morphe/algebra/smith.hpp>
#include <morphe/check.hpp>

#include <algorithm>
#include <random>
#include <set>
#include <string>
#include <vector>

namespace ma = morphe::algebra;
using morphe::arithmetic::Cyclotomic;
using morphe::arithmetic::Integer;
using morphe::arithmetic::Rational;

namespace {

template <class K>
bool is_zero(const std::vector<K>& x) {
  for (const auto& v : x)
    if (!v.is_zero()) return false;
  return true;
}

// The number of conjugacy classes of cyclic subgroups.
std::size_t cyclic_subgroup_classes(const ma::FiniteGroup& G) {
  std::set<std::vector<std::uint32_t>> seen;
  for (std::uint32_t g = 0; g < G.n; g++) {
    std::vector<std::uint32_t> best;
    for (std::uint32_t c = 0; c < G.n; c++) {
      // The subgroup generated by c g c⁻¹, sorted.
      const std::uint32_t h = G.mul(G.mul(c, g), G.inv(c));
      std::vector<std::uint32_t> sub;
      std::uint32_t x = 0;
      do sub.push_back(x), x = G.mul(x, h);
      while (x != 0);
      std::sort(sub.begin(), sub.end());
      if (best.empty() || sub < best) best = sub;
    }
    seen.insert(best);
  }
  return seen.size();
}

}  // namespace

int main() {
  morphe::Suite s;
  std::mt19937_64 g(41);

  // ---- linear algebra over a field ------------------------------------------------------------------------------------------
  {
    int rank = 0, det = 0;
    for (int t = 0; t < 200; t++) {
      const std::size_t r = 1 + g() % 6, c = 1 + g() % 6;
      ma::Matrix A(r, c);
      ma::FieldMatrix<Rational> Q(r, c);
      for (std::size_t i = 0; i < r; i++)
        for (std::size_t j = 0; j < c; j++) {
          const long long v = t % 2 ? static_cast<long long>(g() % 3) - 1 : static_cast<long long>(g() % 11) - 5;
          A(i, j) = v, Q(i, j) = v;
        }
      if (Q.rank() != ma::rank_mod(A, 0)) rank++;
      if (r == c && Q.determinant() != Rational(ma::determinant(A))) det++;
    }
    s.equal("field_matrix: the rank over ℚ equals the Smith form's, 200 integer matrices (failures)", rank, 0);
    s.equal("field_matrix: the determinant over ℚ equals Bareiss's over ℤ (failures)", det, 0);
    int inv = 0, mult = 0;
    for (int t = 0; t < 30; t++) {
      const std::size_t n = 1 + g() % 4;
      ma::FieldMatrix<Cyclotomic> A(n, n), B(n, n);
      for (auto* M : {&A, &B})
        for (auto& x : M->a) {
          std::vector<Rational> c(4);
          for (auto& y : c) y = Rational(Integer(static_cast<long long>(g() % 7) - 3), Integer(static_cast<long long>(1 + g() % 3)));
          x = Cyclotomic::from_basis(5, c);
        }
      if (!(A.determinant() * B.determinant() == (A * B).determinant())) mult++;
      if (!A.determinant().is_zero() && !(A * A.inverse() == ma::FieldMatrix<Cyclotomic>::identity(n))) inv++;
    }
    s.equal("field_matrix: det(A B) = det A det B over ℚ(ζ_5), 30 pairs (failures)", mult, 0);
    s.equal("field_matrix: A A⁻¹ = I over ℚ(ζ_5) (failures)", inv, 0);
  }

  // ---- the group algebra -----------------------------------------------------------------------------------------------------
  {
    int bad = 0;
    for (const auto& G : {ma::symmetric(3), ma::quaternion(), ma::alternating(4)}) {
      const ma::GroupAlgebra<Rational> A(G);
      for (int t = 0; t < 5; t++) {
        std::vector<std::vector<Rational>> x(3, A.zero());
        for (auto& v : x)
          for (auto& c : v) c = Rational(Integer(static_cast<long long>(g() % 7) - 3), Integer(static_cast<long long>(1 + g() % 2)));
        if (A.multiply(A.multiply(x[0], x[1]), x[2]) != A.multiply(x[0], A.multiply(x[1], x[2]))) bad++;
        if (A.multiply(A.one(), x[0]) != x[0] || A.multiply(x[0], A.one()) != x[0]) bad++;
        if (A.multiply(A.basis(1), A.basis(2)) != A.basis(G.mul(1, 2))) bad++;
      }
    }
    s.equal("group_algebra: the convolution is associative with unit 1 and extends the group law, on S_3, Q_8, A_4 (failures)", bad, 0);
  }

  // ---- central idempotents and the Wedderburn blocks ------------------------------------------------------------------------------
  const ma::FiniteGroup F21 = ma::permutation_group({{1, 2, 3, 4, 5, 6, 0}, {0, 2, 4, 6, 1, 3, 5}}, 7, "F21").group;
  const std::vector<ma::FiniteGroup> groups = {ma::cyclic(6), ma::symmetric(3), ma::dihedral(4), ma::quaternion(), ma::alternating(4),
                                               F21, ma::symmetric(4), ma::alternating(5), ma::symmetric(5)};
  {
    int square = 0, orthogonal = 0, sum = 0, central = 0, blocks = 0, components = 0;
    std::string where;
    for (const auto& G : groups) {
      const auto T = ma::character_table(G);
      const ma::GroupAlgebra<Cyclotomic> A(G);
      std::vector<std::vector<Cyclotomic>> e;
      for (std::size_t x = 0; x < T.size(); x++) e.push_back(ma::central_idempotent(T, x));
      auto total = A.zero();
      for (std::size_t x = 0; x < T.size(); x++) {
        if (A.multiply(e[x], e[x]) != e[x]) square++;
        for (std::size_t y = 0; y < T.size(); y++)
          if (y != x && !is_zero(A.multiply(e[x], e[y]))) orthogonal++;
        if (!A.is_central(e[x])) central++;
        total = A.add(total, e[x]);
      }
      if (total != A.one()) sum++;
      for (const auto& B : ma::wedderburn(A, T))
        if (B.dimension != B.degree * B.degree) blocks++, where += G.name + " ";
      // Isotypic components of a random f.
      std::vector<Cyclotomic> f(G.n);
      for (auto& c : f) c = Cyclotomic(static_cast<long long>(g() % 9) - 4);
      const auto parts = ma::isotypic_components(A, T, f);
      auto back = A.zero();
      for (std::size_t x = 0; x < parts.size(); x++) {
        back = A.add(back, parts[x]);
        if (A.multiply(parts[x], e[x]) != parts[x]) components++;
        if (x + 1 < parts.size() && !is_zero(A.multiply(parts[x], e[x + 1]))) components++;
      }
      if (back != f) components++;
    }
    s.equal("group_algebra: e_χ² = e_χ on nine groups up to S_5 (failures)", square, 0);
    s.equal("group_algebra: e_χ e_ψ = 0 for χ ≠ ψ (failures)", orthogonal, 0);
    s.equal("group_algebra: Σ_χ e_χ = 1 (failures)", sum, 0);
    s.equal("group_algebra: every e_χ is central (failures)", central, 0);
    s.require("group_algebra: dim ℂ[G] e_χ = χ(1)², measured as the rank of x ↦ x e_χ: ℂ[G] ≅ ⊕_χ M_{χ(1)}(ℂ)", blocks == 0, where);
    s.equal("group_algebra: the isotypic components f e_χ sum to f and lie in their blocks (failures)", components, 0);
    bool noncentral = false;
    {
      const ma::GroupAlgebra<Cyclotomic> A(ma::symmetric(3));
      noncentral = !A.is_central(A.basis(1)) && A.is_central(A.one());
    }
    s.require("group_algebra: a transposition of S_3 is not central, 1 is", noncentral);
  }

  // ---- the rational blocks ----------------------------------------------------------------------------------------------------------
  {
    int idem = 0, dims = 0, count = 0;
    std::string where;
    for (const auto& G : groups) {
      const auto T = ma::character_table(G);
      const ma::GroupAlgebra<Rational> A(G);
      const auto blocks = ma::rational_wedderburn(A, T);
      auto total = A.zero();
      for (std::size_t b = 0; b < blocks.size(); b++) {
        const auto& e = blocks[b].idempotent;
        if (A.multiply(e, e) != e || !A.is_central(e)) idem++;
        for (std::size_t c = 0; c < blocks.size(); c++)
          if (c != b && !is_zero(A.multiply(e, blocks[c].idempotent))) idem++;
        total = A.add(total, e);
        const std::size_t d = T.degree(blocks[b].characters[0]);
        if (blocks[b].dimension != blocks[b].characters.size() * d * d) dims++, where += G.name + " ";
      }
      if (total != A.one()) idem++;
      if (blocks.size() != cyclic_subgroup_classes(G)) count++, where += G.name + "(count) ";
    }
    s.equal("group_algebra: the rational idempotents are idempotent, central, orthogonal and sum to 1 (failures)", idem, 0);
    s.require("group_algebra: dim_ℚ ℚ[G] e = |orbit| χ(1)² for every Galois orbit", dims == 0, where);
    s.require("group_algebra: as many rational blocks as conjugacy classes of cyclic subgroups", count == 0, where);
  }

  // ---- ℚ[C_n] ≅ ⊕_{d | n} ℚ(ζ_d) ------------------------------------------------------------------------------------------------
  {
    int divisors = 0, dims = 0, fields = 0;
    for (std::size_t n = 1; n <= 18; n++) {
      const auto blocks = ma::cyclic_rational_decomposition(n);
      std::vector<std::size_t> got, want;
      for (const auto& B : blocks) got.push_back(B.divisor);
      for (std::size_t d = 1; d <= n; d++)
        if (n % d == 0) want.push_back(d);
      if (got != want) divisors++;
      const ma::GroupAlgebra<Rational> A(ma::cyclic(n));
      for (const auto& B : blocks) {
        const std::size_t d = B.divisor, phi = morphe::arithmetic::euler_phi(d);
        if (B.block.dimension != phi) dims++;
        // Φ_d(g) e = 0 for the generator g, and e, g e, …, g^{φ(d)−1} e are independent.
        const auto& e = B.block.idempotent;
        const auto P = morphe::arithmetic::cyclotomic_polynomial(static_cast<unsigned>(d));
        auto phi_g = A.zero();
        for (std::size_t i = 0; i < P.size(); i++) phi_g[i % n] += Rational(P[i]);
        if (!is_zero(A.multiply(phi_g, e))) fields++;
        ma::FieldMatrix<Rational> powers(phi, n);
        auto u = e;
        for (std::size_t i = 0; i < phi; i++) {
          for (std::size_t k = 0; k < n; k++) powers(i, k) = u[k];
          u = A.multiply(A.basis(n > 1 ? 1u : 0u), u);
        }
        if (powers.rank() != phi) fields++;
      }
    }
    s.equal("group_algebra: the blocks of ℚ[C_n] are indexed by the divisors d of n, n ≤ 18 (failures)", divisors, 0);
    s.equal("group_algebra: the block of d has dimension φ(d) (failures)", dims, 0);
    s.equal("group_algebra: the block of d is ℚ[u] with Φ_d(u) = 0 and 1, …, u^{φ(d)−1} independent: ℚ(ζ_d) (failures)", fields, 0);
  }
  return s.done();
}
