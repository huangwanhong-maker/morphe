struct FiniteGroup {
  std::size_t n = 1;
  std::vector<std::uint32_t> table{0};  // table[a n + b] = a b
  std::vector<std::uint32_t> inverses{0};
  std::string name = "1";

  std::size_t order() const { return n; }
  std::uint32_t mul(std::uint32_t a, std::uint32_t b) const { return table[a * n + b]; }
  std::uint32_t inv(std::uint32_t a) const { return inverses[a]; }
  static constexpr std::uint32_t identity() { return 0; }

  // From a table whose identity is element 0; throws std::invalid_argument unless it is a group.
  static FiniteGroup from_table(std::size_t n, std::vector<std::uint32_t> table, std::string name) {
    FiniteGroup G;
    G.n = n;
    G.table = std::move(table);
    G.name = std::move(name);
    if (G.table.size() != n * n) throw std::invalid_argument("morphe::algebra::FiniteGroup: the table is not n × n");
    for (std::uint32_t a = 0; a < n; a++) {
      if (G.mul(0, a) != a || G.mul(a, 0) != a) throw std::invalid_argument("morphe::algebra::FiniteGroup: 0 is not the identity");
      std::vector<char> row(n, 0);
      for (std::uint32_t b = 0; b < n; b++) {
        if (G.mul(a, b) >= n || row[G.mul(a, b)]++) throw std::invalid_argument("morphe::algebra::FiniteGroup: a row is not a permutation");
      }
    }
    for (std::uint32_t a = 0; a < n; a++)
      for (std::uint32_t b = 0; b < n; b++)
        for (std::uint32_t c = 0; c < n; c++)
          if (G.mul(G.mul(a, b), c) != G.mul(a, G.mul(b, c))) throw std::invalid_argument("morphe::algebra::FiniteGroup: not associative");
    G.inverses.assign(n, 0);
    for (std::uint32_t a = 0; a < n; a++)
      for (std::uint32_t b = 0; b < n; b++)
        if (G.mul(a, b) == 0) G.inverses[a] = b;
    return G;
  }

  // The value of a word under generator images (1-based letters).
  std::uint32_t evaluate(const Word& w, const std::vector<std::uint32_t>& images) const {
    std::uint32_t g = 0;
    for (int x : w) {
      const std::uint32_t h = images[static_cast<std::size_t>(std::abs(x)) - 1];
      g = mul(g, x > 0 ? h : inv(h));
    }
    return g;
  }
  std::uint32_t element_order(std::uint32_t a) const {
    std::uint32_t k = 1, g = a;
    while (g != 0) g = mul(g, a), k++;
    return k;
  }
  bool is_abelian() const {
    for (std::uint32_t a = 0; a < n; a++)
      for (std::uint32_t b = 0; b < a; b++)
        if (mul(a, b) != mul(b, a)) return false;
    return true;
  }
};

using Permutation = std::vector<std::uint32_t>;  // p[i]: the image of i

// The group generated by permutations of {0..d-1}, by closure (breadth first); composition
// (p q)(i) = p(q(i)), so q acts first. The identity is element 0; elements[i] is element i.
struct PermutationGroup {
  FiniteGroup group;
  std::vector<Permutation> elements;
};

inline PermutationGroup permutation_group(const std::vector<Permutation>& generators, std::size_t degree, std::string name,
                                          std::size_t limit = 50000) {
  auto compose = [](const Permutation& p, const Permutation& q) {
    Permutation r(q.size());
    for (std::size_t i = 0; i < q.size(); i++) r[i] = p[q[i]];
    return r;
  };
  Permutation id(degree);
  std::iota(id.begin(), id.end(), 0u);
  std::vector<Permutation> el{id};
  std::map<Permutation, std::uint32_t> index{{id, 0}};
  for (std::size_t k = 0; k < el.size(); k++)
    for (const auto& g : generators) {
      Permutation h = compose(g, el[k]);
      if (!index.count(h)) {
        if (el.size() >= limit) throw std::length_error("morphe::algebra::permutation_group: more than the limit of elements");
        index[h] = static_cast<std::uint32_t>(el.size());
        el.push_back(std::move(h));
      }
    }
  const std::size_t n = el.size();
  std::vector<std::uint32_t> table(n * n);
  for (std::size_t a = 0; a < n; a++)
    for (std::size_t b = 0; b < n; b++) table[a * n + b] = index.at(compose(el[a], el[b]));
  PermutationGroup P;
  P.group.n = n;
  P.group.table = std::move(table);
  P.group.name = std::move(name);
  P.group.inverses.assign(n, 0);
  for (std::uint32_t a = 0; a < n; a++)
    for (std::uint32_t b = 0; b < n; b++)
      if (P.group.mul(a, b) == 0) P.group.inverses[a] = b;
  P.elements = std::move(el);
  return P;
}

// ℤ/n, element k standing for k (mod n).
inline FiniteGroup cyclic(std::size_t n) {
  std::vector<std::uint32_t> t(n * n);
  for (std::size_t a = 0; a < n; a++)
    for (std::size_t b = 0; b < n; b++) t[a * n + b] = static_cast<std::uint32_t>((a + b) % n);
  return FiniteGroup::from_table(n, std::move(t), "Z" + std::to_string(n));
}

// The dihedral group of order 2n, the symmetries of a regular n-gon.
inline FiniteGroup dihedral(std::size_t n) {
  Permutation r(n), s(n);
  for (std::size_t i = 0; i < n; i++) r[i] = static_cast<std::uint32_t>((i + 1) % n), s[i] = static_cast<std::uint32_t>((n - i) % n);
  return permutation_group({r, s}, n, "D" + std::to_string(n)).group;
}

// The symmetric group S_n (n <= 7), generated by a transposition and an n-cycle.
inline FiniteGroup symmetric(std::size_t n) {
  if (n > 7) throw std::invalid_argument("morphe::algebra::symmetric: n > 7");
  if (n <= 1) return FiniteGroup{};
  Permutation t(n), c(n);
  std::iota(t.begin(), t.end(), 0u);
  std::swap(t[0], t[1]);
  for (std::size_t i = 0; i < n; i++) c[i] = static_cast<std::uint32_t>((i + 1) % n);
  return permutation_group({t, c}, n, "S" + std::to_string(n)).group;
}

// The alternating group A_n (3 <= n <= 7), generated by the 3-cycles (0 1 k).
inline FiniteGroup alternating(std::size_t n) {
  if (n < 3 || n > 7) throw std::invalid_argument("morphe::algebra::alternating: n outside 3..7");
  std::vector<Permutation> gens;
  for (std::size_t k = 2; k < n; k++) {
    Permutation p(n);
    std::iota(p.begin(), p.end(), 0u);
    p[0] = 1, p[1] = static_cast<std::uint32_t>(k), p[k] = 0;
    gens.push_back(p);
  }
  return permutation_group(gens, n, "A" + std::to_string(n)).group;
}

// The quaternion group Q8 = {±1, ±i, ±j, ±k}, as permutations of itself by left multiplication.
inline FiniteGroup quaternion() {
  // Elements 0..7: 1, i, j, k, -1, -i, -j, -k; the product of units, with signs.
  static const int unit[4][4] = {{0, 1, 2, 3}, {1, 4, 3, 6}, {2, 7, 4, 1}, {3, 2, 5, 4}};  // 1,i,j,k times 1,i,j,k (4.. = negatives)
  std::vector<std::uint32_t> t(64);
  for (int a = 0; a < 8; a++)
    for (int b = 0; b < 8; b++) {
      int p = unit[a % 4][b % 4];
      const int sign = (a / 4 + b / 4 + p / 4) % 2;
      t[static_cast<std::size_t>(a * 8 + b)] = static_cast<std::uint32_t>(p % 4 + 4 * sign);
    }
  return FiniteGroup::from_table(8, std::move(t), "Q8");
}

// G × H, the element (g, h) numbered g |H| + h.
inline FiniteGroup direct_product(const FiniteGroup& G, const FiniteGroup& H) {
  const std::size_t n = G.n * H.n;
  std::vector<std::uint32_t> t(n * n);
  for (std::uint32_t a = 0; a < n; a++)
    for (std::uint32_t b = 0; b < n; b++)
      t[a * n + b] = static_cast<std::uint32_t>(G.mul(static_cast<std::uint32_t>(a / H.n), static_cast<std::uint32_t>(b / H.n)) * H.n +
                                                H.mul(static_cast<std::uint32_t>(a % H.n), static_cast<std::uint32_t>(b % H.n)));
  return FiniteGroup::from_table(n, std::move(t), G.name + "×" + H.name);
}

// The conjugacy classes, each sorted, the class of the identity first.
inline std::vector<std::vector<std::uint32_t>> conjugacy_classes(const FiniteGroup& G) {
  std::vector<int> cls(G.n, -1);
  std::vector<std::vector<std::uint32_t>> out;
  for (std::uint32_t a = 0; a < G.n; a++) {
    if (cls[a] >= 0) continue;
    std::vector<std::uint32_t> c;
    for (std::uint32_t g = 0; g < G.n; g++) {
      const std::uint32_t b = G.mul(G.mul(g, a), G.inv(g));
      if (cls[b] < 0) cls[b] = static_cast<int>(out.size()), c.push_back(b);
    }
    std::sort(c.begin(), c.end());
    out.push_back(std::move(c));
  }
  return out;
}

// Calls f(images) for every homomorphism ⟨x_1..x_m | R⟩ → G; f returns false to stop.
// Returns the number visited.
inline std::uint64_t for_each_homomorphism(const Presentation& P, const FiniteGroup& G,
                                           const std::function<bool(const std::vector<std::uint32_t>&)>& f) {
  const std::size_t m = P.generators;
  // The relators to test once generator k is assigned: those whose largest generator is k.
  std::vector<std::vector<const Word*>> due(m + 1);
  for (const auto& r : P.relators) {
    std::size_t top = 0;
    for (int x : r) top = std::max(top, static_cast<std::size_t>(std::abs(x)));
    due[top].push_back(&r);
  }
  for (const Word* r : due[0])
    if (!r->empty()) return 0;  // cannot happen: a nonempty word has a generator
  std::vector<std::uint32_t> img(m, 0);
  std::uint64_t count = 0;
  bool stop = false;
  std::function<void(std::size_t)> go = [&](std::size_t k) {
    if (stop) return;
    if (k == m) {
      count++;
      if (!f(img)) stop = true;
      return;
    }
    for (std::uint32_t g = 0; g < G.n && !stop; g++) {
      img[k] = g;
      bool ok = true;
      for (const Word* r : due[k + 1])
        if (G.evaluate(*r, img) != 0) { ok = false; break; }
      if (ok) go(k + 1);
    }
  };
  go(0);
  return count;
}

inline std::uint64_t count_homomorphisms(const Presentation& P, const FiniteGroup& G) {
  return for_each_homomorphism(P, G, [](const std::vector<std::uint32_t>&) { return true; });
}

