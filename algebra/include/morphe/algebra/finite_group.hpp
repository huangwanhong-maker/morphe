// Finite groups by their multiplication tables, and homomorphisms into them.
//
// A FiniteGroup of order n has elements 0..n-1, the identity being 0, and its table
// mul(a, b) = a b. Tables are built for the cyclic, dihedral, symmetric, alternating and
// quaternion groups, for direct products, and for the closure of a set of permutations; a
// table given from outside is checked against the group axioms (O(n^3) for associativity).
//
// Homomorphisms from a finitely presented group ⟨x_1..x_m | r_1..r_k⟩ into G are the
// assignments x_i ↦ g_i under which every relator evaluates to the identity (von Dyck's
// theorem; Lyndon and Schupp 1977, §II.1). They are enumerated by backtracking over the
// generators, testing each relator as soon as all its generators are assigned: exact, and
// O(|G|^m) in the worst case. Their number is a topological invariant when the group is a
// fundamental group: for a closed orientable surface of genus g it is
// |G|^{2g-1} Σ_ρ (dim ρ)^{2-2g}, summed over the irreducible complex representations
// (Frobenius 1896; Mednykh 1978), which the checks use.

