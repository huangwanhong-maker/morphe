// Grammars written in BNF over bytes, compiled to context-free grammars, parsed by Earley's
// parser into named trees, with diagnostics that say exactly how far a text is right.
//
// A notation that people write (a variant's description, a karyotype, a date, a unit) is a
// language over bytes; its grammar is best written once, in the extended Backus–Naur form of the
// standard that defines it (Backus 1959; Naur et al. 1960; ISO/IEC 14977:1996 for the extensions),
// and read by a parser that decides every context-free grammar. This header reads such a text:
//
//   # a comment, to the end of the line
//   name     ::= alternative | alternative ;     a rule; the first rule is the start
//   item       = name                             a nonterminal
//              | "literal" | 'literal'            a word (\" \' \\ \n \t \xHH escape; "" is ε)
//              | [A-Za-z0-9_] | [^)]              a class of bytes (ranges, \] \\ \- \^ \n \t \xHH)
//              | ( alternatives )                 a group
//              | item? | item* | item+            at most once, any number of times, at least once
//
// A name is [A-Za-z_][A-Za-z0-9_]*; one beginning with '_' is hidden: its node is spliced into its
// parent in the named tree, as are the helpers made for groups, repetitions and classes.
//
// Compilation.
// - Terminals are the atoms of the Boolean algebra of byte sets generated by the grammar's
//   classes and the letters of its literals: two bytes are one terminal exactly when every class
//   and literal treats them alike (the coarsest partition refining all of them, the "byte
//   classes" of a lexer generator). A class is the union of its atoms: a single terminal when it is
//   one atom, which is the usual case ([0-9] where no literal names a digit), and otherwise a
//   hidden nonterminal with one rule per atom. Bytes that no class or literal holds form one more
//   atom, which no rule uses. The grammar is thus over at most 257 letters and usually a few dozen.
// - x? is X → ε | x; x* is X → ε | X x; x+ is X → x | X x (left recursion, which Earley's parser
//   completes in linear space on such lists); a group is a nonterminal with its alternatives.
// - The translation is a bijection between the parse trees of the text grammar (with the
//   repetitions read as their least derivations) and those of the compiled grammar, so the named
//   tree read back is the text grammar's derivation of the input.
//
// Parsing is morphe::formal::Earley's (Earley 1970; Aycock and Horspool 2002), O(n³) in general
// and O(n²) on unambiguous grammars. Diagnostics come from its chart: the furthest viable prefix,
// and the literals and classes that may follow it, each literal shown from where the text left it
// ("'l' (of 'del')"). They describe a prefix of a word of the language exactly when every
// nonterminal is productive (Earley's header); compile_bnf reports unproductive rules.

